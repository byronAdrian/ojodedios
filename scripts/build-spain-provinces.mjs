#!/usr/bin/env node
/**
 * Regenerates server/geo/spainProvinces.data.js — the province polygons used to
 * assign a comunidad autónoma / provincia to camera coordinates server-side.
 *
 * Source: Natural Earth admin-1 (public domain), as curated (simplified at
 * ~0.01°, delta-encoded) by bilawalsidhu/gods-eye-view at a pinned commit so
 * the output is reproducible. Usage: npm run data:spain [-- <local-file>]
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const PINNED_SOURCE =
  'https://raw.githubusercontent.com/bilawalsidhu/gods-eye-view/e7707d9a0f34d9fbffc300023c319f95caa5be30/src/data/local_data/natural_earth/states_provinces.json';
const OUTPUT = fileURLToPath(
  new URL('../server/geo/spainProvinces.data.js', import.meta.url),
);

async function loadSource(localPath) {
  if (localPath) return JSON.parse(await readFile(localPath, 'utf8'));
  const response = await fetch(PINNED_SOURCE, {
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) throw new Error(`Download failed: HTTP ${response.status}`);
  return response.json();
}

/** Decode one ring: first vertex absolute, then [dLon, dLat] deltas, in 10^-d degrees. */
function decodeRing(encoded, decimals) {
  const scale = 10 ** decimals;
  const ring = [];
  let lon = 0;
  let lat = 0;
  for (let i = 0; i < encoded.length; i += 2) {
    lon += encoded[i];
    lat += encoded[i + 1];
    ring.push([lon / scale, lat / scale]);
  }
  return ring;
}

const source = await loadSource(process.argv[2]);
const defaultDecimals = source.meta?.decimals ?? 3;
const provinces = source.features
  .filter((feature) => feature.iso2 === 'ES')
  .map((feature) => {
    const decimals = feature.d ?? defaultDecimals;
    // polygons[] = list of polygons, each a list of rings (outer first, holes after).
    const polygons = feature.polygons.map((polygon) =>
      (Array.isArray(polygon[0]) ? polygon : [polygon]).map((ring) =>
        decodeRing(ring, decimals),
      ),
    );
    const all = polygons.flat(2);
    const lons = all.map((p) => p[0]);
    const lats = all.map((p) => p[1]);
    return {
      iso: feature.iso,
      bbox: [
        Math.min(...lons),
        Math.min(...lats),
        Math.max(...lons),
        Math.max(...lats),
      ],
      polygons,
    };
  })
  .sort((a, b) => a.iso.localeCompare(b.iso));

if (provinces.length !== 52) {
  throw new Error(`Expected 52 Spanish provinces, got ${provinces.length}`);
}

await writeFile(
  OUTPUT,
  '// Generated by scripts/build-spain-provinces.mjs — do not edit by hand.\n' +
    'export default ' +
    JSON.stringify({
    meta: {
      source: PINNED_SOURCE,
      license: 'Public domain — Natural Earth (naturalearthdata.com)',
      schema: 'provinces[]: iso (ISO 3166-2), bbox [w,s,e,n], polygons[][ring][[lon,lat]] (first ring outer)',
    },
    provinces,
  }) +
    ';\n',
);
console.log(`Wrote ${provinces.length} provinces to ${OUTPUT}`);
